#!/usr/bin/env bash
# Point Formula/sprig.rb at a published release: scripts/update-formula.sh 0.1.2
#
# This repo doubles as the Homebrew tap, so run this after the Release workflow
# has published v<version>, then commit and push Formula/sprig.rb to main.
set -euo pipefail
cd "$(dirname "$0")/.."

version=${1:?usage: scripts/update-formula.sh <version>}
version=${version#v}
repo=john-rock/sprig
sums_url="https://github.com/$repo/releases/download/v$version/SHA256SUMS"

sums=$(curl -fsSL "$sums_url") || { echo "couldn't download $sums_url (is v$version published?)" >&2; exit 1; }

sha() {
  local name="sprig-$version-$1.tar.gz" sum
  sum=$(awk -v n="$name" '$2 == n { print $1 }' <<<"$sums")
  if [[ ! $sum =~ ^[0-9a-f]{64}$ ]]; then
    echo "no checksum for $name in $sums_url" >&2
    exit 1
  fi
  echo "$sum"
}

darwin_arm64=$(sha darwin-arm64)
darwin_x64=$(sha darwin-x64)
linux_arm64=$(sha linux-arm64)
linux_x64=$(sha linux-x64)

tmp=$(mktemp)
cat >"$tmp" <<EOF
# Homebrew formula. This repo is its own tap:
#   brew tap john-rock/sprig https://github.com/john-rock/sprig
#   brew install john-rock/sprig/sprig && sprig install
#
# Generated by scripts/update-formula.sh from the release's SHA256SUMS.
# Don't edit the version or checksums by hand.
class Sprig < Formula
  desc "Fig-style IDE autocomplete for zsh, powered by Fig's completion specs"
  homepage "https://github.com/$repo"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "https://github.com/$repo/releases/download/v#{version}/sprig-#{version}-darwin-arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "https://github.com/$repo/releases/download/v#{version}/sprig-#{version}-darwin-x64.tar.gz"
      sha256 "$darwin_x64"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/$repo/releases/download/v#{version}/sprig-#{version}-linux-arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "https://github.com/$repo/releases/download/v#{version}/sprig-#{version}-linux-x64.tar.gz"
      sha256 "$linux_x64"
    end
  end

  def install
    bin.install "bin/sprig"
    (share/"sprig").install "share/sprig/specs"
    doc.install Dir["share/doc/sprig/*"]
  end

  def caveats
    <<~EOS
      Finish setup with:
        sprig install
      then open a new terminal tab.
    EOS
  end

  test do
    assert_match "checkout", shell_output("#{bin}/sprig complete 'git ch'")
  end
end
EOF
mv "$tmp" Formula/sprig.rb
echo "Formula/sprig.rb -> $version"
